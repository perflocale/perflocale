foreach ( $perflocale_languages as &$perflocale_lang_entry ) {
	$perflocale_locale = $perflocale_lang_entry['locale'] ?? '';

	if ( isset( $perflocale_locale_formats[ $perflocale_locale ] ) ) {
		[ $perflocale_df, $perflocale_tf ] = $perflocale_locale_formats[ $perflocale_locale ];
	} else {
		$perflocale_family = strtok( $perflocale_locale, '_' );
		if ( $perflocale_family && isset( $perflocale_family_formats[ $perflocale_family ] ) ) {
			[ $perflocale_df, $perflocale_tf ] = $perflocale_family_formats[ $perflocale_family ];
		} else {
			$perflocale_df = 'F j, Y';
			$perflocale_tf = 'g:i a';
		}
	}

	$perflocale_lang_entry['date_format'] = $perflocale_df;
	$perflocale_lang_entry['time_format'] = $perflocale_tf;
}
unset( $perflocale_lang_entry );

